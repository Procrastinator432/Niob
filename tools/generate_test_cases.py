    def roots(fun, lo, hi, n=20000):
        """All sign changes of fun on [lo, hi] (dense scan, then bisection to full precision)."""
        out = []
        xs = [lo + (hi - lo) * mp.mpf(i) / n for i in range(n + 1)]
        vs = [fun(t) for t in xs]
        for i in range(n):
            if vs[i] == 0:
                out.append(xs[i])
            elif vs[i] * vs[i + 1] < 0:
                a, b = xs[i], xs[i + 1]
                for _ in range(140):
                    m = (a + b) / 2
                    if fun(a) * fun(m) <= 0:
                        b = m
                    else:
                        a = m
                out.append((a + b) / 2)
        return out



def polynomials():
    rnd = random.Random(4)
    y, z, w = sp.symbols('y z w')

    def lin(vs):
        v = rnd.choice(vs)
        a = rnd.choice([1, 2, 3, -1, sp.Rational(1, 2), sp.Rational(-2, 3), sp.Rational(1, 10)])
        b = rnd.choice([0, 1, -1, 2, sp.Rational(1, 3), sp.Rational(1, 2)])
        extra = rnd.choice(vs) * rnd.choice([0, 0, 1, -2]) if len(vs) > 1 else 0
        return a * v + b + extra

    rows = []
    seen = set()
    while len(rows) < 200:
        vs = rnd.choice([[y], [y], [y, z], [y, z, w]])
        k = rnd.random()
        if k < 0.4:
            e = lin(vs) ** rnd.randint(2, 12)
        elif k < 0.7:
            e = lin(vs) * lin(vs) * rnd.choice([1, lin(vs)])
        elif k < 0.85:
            e = lin(vs) ** rnd.randint(2, 6) - lin(vs) ** rnd.randint(1, 4)
        else:
            e = (lin(vs) ** 2) * rnd.choice([y, y ** 2, 3 * y])
        t = sp.sstr(e).replace('**', '^').replace(' ', '')
        if t in seen:
            continue
        seen.add(t)
        pts = []
        for _ in range(3):
            sub = {s: sp.Rational(rnd.randint(-200, 200), 100) for s in (y, z, w)}
            val = e.subs(sub)
            pts.append(','.join(f'{s}={num(sub[s])}' for s in (y, z, w)) + ':' + num(val))
        rows.append([f'poly_{len(rows):04d}', t, t, 'polynomial', ';'.join(pts), '1e-9', '1e-9', 'rad'])
    write('polynomials.tsv', rows,
          'Products and powers of linear terms in y, z, w. polynomial: the result must be expanded (no ")^", ")*(" or ")(") '
          'and agree with the input at the sample points y=..,z=..,w=..:value.')



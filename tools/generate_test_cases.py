X = sp.Symbol('x', real=True)


def derivatives():
    # (calculator text, sympy expression, points where it is singular or not smooth)
    functions = [
        ('sin(x)', sp.sin(X), []), ('cos(x)', sp.cos(X), []), ('tan(x)', sp.tan(X), ['tanpoles']),
        ('exp(x)', sp.exp(X), []), ('ln(x)', sp.log(X), [0]), ('sqrt(x)', sp.sqrt(X), [0]),
        ('x^3', X ** 3, []), ('x^(1/3)', sp.cbrt(X), [0]), ('1/x', 1 / X, [0]), ('atan(x)', sp.atan(X), []),
        ('asin(x)', sp.asin(X), [-1, 1]), ('acos(x)', sp.acos(X), [-1, 1]), ('sinh(x)', sp.sinh(X), []),
        ('cosh(x)', sp.cosh(X), []), ('tanh(x)', sp.tanh(X), []), ('exp(-x^2)', sp.exp(-X ** 2), []),
        ('x*sin(x)', X * sp.sin(X), []), ('ln(1+x^2)', sp.log(1 + X ** 2), []),
        ('sqrt(1+x^2)', sp.sqrt(1 + X ** 2), []), ('cos(x)+1000', sp.cos(X) + 1000, []),
        ('x^2+1000000', X ** 2 + 10 ** 6, []), ('exp(x)-1', sp.exp(X) - 1, []), ('1/(1+x^2)', 1 / (1 + X ** 2), []),
        ('sin(x)/x', sp.sin(X) / X, [0]), ('x^5-3*x^2', X ** 5 - 3 * X ** 2, []),
        ('exp(sin(x))', sp.exp(sp.sin(X)), []), ('ln(x)^2', sp.log(X) ** 2, [0]), ('x^x', X ** X, [0]),
        ('1/x^2', 1 / X ** 2, [0]), ('sin(x^2)', sp.sin(X ** 2), []), ('1/sqrt(x)', 1 / sp.sqrt(X), [0]),
        ('x*ln(x)', X * sp.log(X), [0]), ('atan(1/x)', sp.atan(1 / X), [0]), ('exp(-1/x^2)', sp.exp(-1 / X ** 2), [0]),
        ('cos(100*x)', sp.cos(100 * X), []), ('sin(1000*x)', sp.sin(1000 * X), []),
    ]
    base = [1e-9, 1e-6, 1e-4, 1e-2, 0.3, 1.0, 3.0, 10.0, 100.0, 1e4, 1e6]
    points = sorted(set(base + [-p for p in base]))
    rows = []
    for txt, f, sing in functions:
        df = sp.diff(f, X)
        for p in points:
            pv = sp.Float(repr(p), 50)
            try:
                fv = complex(f.subs(X, pv).evalf(40))
                dv = complex(df.subs(X, pv).evalf(40))
            except (TypeError, ValueError, ZeroDivisionError):
                continue
            if fv.imag != 0 or dv.imag != 0 or not math.isfinite(dv.real) or not math.isfinite(fv.real):
                continue
            scale = max(1.0, abs(p))
            near = False
            for s in sing:
                if s == 'tanpoles':
                    k = round(p / math.pi - 0.5)
                    near = near or abs(p - (k + 0.5) * math.pi) < 1e-3 * scale
                else:
                    near = near or abs(p - s) < 1e-3 * scale
            # Central differences lose everything when f is huge compared with f' * scale.
            ill = abs(dv.real) * scale < 1e-6 * abs(fv.real) if fv.real != 0 else False
            check = 'number_or_error' if (near or ill) else 'number'
            expr = f'deriv({txt},x,{num(p)})'
            rows.append([f'deriv_{len(rows):04d}', expr, expr, check, num(dv.real), '1e-12', '1e-6', 'rad'])
    # Close to poles: a correct value or an explicit error, never a wrong value.
    poles = [('1/x^2', 1 / X ** 2, 0), ('1/x', 1 / X, 0), ('1/(x-3)^2', 1 / (X - 3) ** 2, 3), ('1/(x-3)', 1 / (X - 3), 3),
             ('ln(abs(x))', sp.log(sp.Abs(X)), 0), ('atan(1/x)', sp.atan(1 / X), 0), ('1/x^3', 1 / X ** 3, 0),
             ('exp(1/x)', sp.exp(1 / X), 0), ('1/sin(x)', 1 / sp.sin(X), 0), ('tan(x)', sp.tan(X), sp.pi / 2),
             ('1/(x^2-1)', 1 / (X ** 2 - 1), 1), ('x/(x-0.5)', X / (X - sp.Rational(1, 2)), sp.Rational(1, 2))]
    for txt, f, c in poles:
        df = sp.diff(f, X)
        for d in [1e-9, 1e-7, 1e-5, 1e-4, 3e-4, 1e-3, 1e-2]:
            for sgn in (1, -1):
                p = float(sp.N(c, 40)) + sgn * d
                pv = sp.Float(repr(p), 50)
                dv = complex(df.subs(X, pv).evalf(40))
                if dv.imag != 0 or not math.isfinite(dv.real):
                    continue
                expr = f'deriv({txt},x,{num(p)})'
                if any(r[1] == expr for r in rows):
                    continue
                rows.append([f'deriv_pole_{len(rows):04d}', expr, expr, 'number_or_error', num(dv.real), '1e-12', '1e-6', 'rad'])
    # Jumps and kinks: no derivative exists, an explicit error is required.
    for txt, p in [('floor(x)', 1), ('floor(x)', -2), ('floor(x)', 0), ('ceil(x)', 3), ('sign(x)', 0),
                   ('abs(x)', 0), ('abs(x-2)', 2), ('round(x)', 0.5), ('floor(10*x)', 0.3)]:
        expr = f'deriv({txt},x,{num(p)})'
        rows.append([f'deriv_jump_{len(rows):04d}', expr, expr, 'error', 'no derivative at a jump or kink', '0', '0', 'rad'])
    for txt, p, v in [('floor(x)', 0.5, 0), ('sign(x)', 0.3, 0), ('abs(x)', -0.7, -1), ('abs(x)', 2.5, 1)]:
        expr = f'deriv({txt},x,{num(p)})'
        rows.append([f'deriv_jump_{len(rows):04d}', expr, expr, 'number', num(v), '1e-9', '0', 'rad'])
    write('derivatives.tsv', rows,
          'Numeric derivatives at points over many orders of magnitude, close to poles, and at jumps. '
          'number_or_error: a correct value or an explicit error is accepted, a wrong value is not.')



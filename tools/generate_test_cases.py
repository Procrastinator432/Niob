#!/usr/bin/env python3
"""Generate the shared test fixtures in app/tests/data/generated/.

The fixtures hold randomly generated cases together with reference values that
are computed independently of both calculator engines: sympy and mpmath for
calculus and matrices, Python's exact integers and fractions for big numbers.
Rust (app/tests/generated.rs) and Android (GeneratedCases.java) read the same
files, so both engines are checked against the same references.

The random seeds are fixed. Running the script again reproduces the files, so
the fixtures only change when this script changes.

Requirements: Python 3.9+, sympy and mpmath (pip install sympy mpmath).
Usage:        python tools/generate_test_cases.py
"""
import math
import os
import random
from fractions import Fraction

import mpmath as mp
import sympy as sp

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'app', 'tests', 'data', 'generated')
mp.mp.dps = 50

HEADER = ('# Generated by tools/generate_test_cases.py. Do not edit by hand; change the script and regenerate.\n'
          '# id\tandroid_expression\trust_expression\tcheck\texpected\tabsolute_tolerance\trelative_tolerance\tmode\n')


def num(v):
    """Shortest round-trip text of a float."""
    v = float(v)
    if v == 0:
        return '0'
    return repr(v)


def write(name, rows, note):
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name)
    ids = set()
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER)
        f.write('# ' + note + '\n')
        for row in rows:
            assert len(row) == 8, row
            assert row[0] not in ids, row[0]
            assert all('\t' not in str(c) and '\n' not in str(c) for c in row), row
            ids.add(row[0])
            f.write('\t'.join(str(c) for c in row) + '\n')
    print(f'{name}: {len(rows)} cases')



def exact_numbers():
    rnd = random.Random(5)

    def rint():
        d = rnd.choice([1, 3, 10, 19, 20, 30, 39, 40, 60])
        v = rnd.randint(10 ** (d - 1), 10 ** d - 1)
        return -v if rnd.random() < 0.25 else v

    def gen(depth=0):
        r = rnd.random()
        if depth > 2 or r < 0.3:
            v = rint()
            return (str(v) if v >= 0 else f'({v})'), Fraction(v)
        op = rnd.choice(['+', '-', '*', '*', '/', '^', 'mod', '!'])
        if op == '^':
            b = rnd.choice([2, 3, 7, 10, -2, -3, 12345, 999999999])
            e = rnd.randint(0, 130)
            return (f'{b}^{e}' if b >= 0 else f'({b})^{e}'), Fraction(b) ** e
        if op == '!':
            n = rnd.randint(0, 60)
            return f'{n}!', Fraction(math.factorial(n))
        a, av = gen(depth + 1)
        b, bv = gen(depth + 1)
        if op == '/':
            if bv == 0:
                return a, av
            return f'({a})/({b})', av / bv
        if op == 'mod':
            if av.denominator != 1 or bv.denominator != 1 or bv <= 0:
                return a, av
            return f'({a}) mod ({b})', Fraction(av.numerator % bv.numerator)
        return f'({a}){op}({b})', (av + bv if op == '+' else av - bv if op == '-' else av * bv)

    rows = []
    seen = set()
    while len(rows) < 400:
        t, v = gen()
        if t in seen or abs(v.numerator) > 10 ** 300 or v.denominator > 10 ** 300:
            continue
        seen.add(t)
        if v.denominator == 1:
            rows.append([f'exact_{len(rows):04d}', t, t, 'exact_integer', str(v.numerator), '0', '0', 'rad'])
        else:
            rows.append([f'exact_{len(rows):04d}', t, t, 'exact_fraction', f'{v.numerator}/{v.denominator}', '0', '1e-10', 'rad'])
    write('exact_numbers.tsv', rows,
          'Integer and fraction arithmetic up to 300 digits, including mod and factorials. exact_integer: the exact text must be '
          'the integer. exact_fraction: the exact fraction, or a decimal within the relative tolerance.')



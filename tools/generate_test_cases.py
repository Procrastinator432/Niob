def integrals():
    rnd = random.Random(7)
    rows = []

    def add(expr, ref, kind, abs_tol=1e-12):
        rows.append([f'int_{kind}_{len(rows):04d}', expr, expr, 'integral', num(ref), num(abs_tol), '1e-7', 'rad'])

    # Counts are kept moderate: each numeric integral costs about 0.1 s in a debug build.
    for _ in range(40):
        a, b = rnd.choice([(0, 1), (0, 10), (0, 1000), (-1000, 1000), (0, 100000), (-1e5, 1e5), (-3, 7)])
        c = round(rnd.uniform(a, b), rnd.choice([1, 2, 3, 4]))
        k = 10 ** rnd.choice([0, 1, 2, 3, 4, 6, 8, 10, 12])
        ref = mp.sqrt(mp.pi / k) / 2 * (mp.erf(mp.sqrt(k) * (b - mp.mpf(str(c)))) - mp.erf(mp.sqrt(k) * (a - mp.mpf(str(c)))))
        add(f'int(exp(-(x-({c}))^2*{k}),x,{a:g},{b:g})', ref, 'gauss')
    for _ in range(20):
        a, b = rnd.choice([(0, 1), (0, 1000), (-1000, 1000), (0, 100000)])
        c = round(rnd.uniform(a, b), rnd.choice([1, 2, 3]))
        k = 10 ** rnd.choice([0, 2, 4, 6, 8, 10])
        cc = mp.mpf(str(c))
        ref = (mp.atan(mp.sqrt(k) * (b - cc)) - mp.atan(mp.sqrt(k) * (a - cc))) / mp.sqrt(k)
        add(f'int(1/(1+(x-({c}))^2*{k}),x,{a:g},{b:g})', ref, 'lorentz')
    for _ in range(40):
        k = 10 ** rnd.choice([0, 1, 2, 3, 4, 6, 8])
        b = rnd.choice([1, 10, 100, 1e4, 1e6])
        add(f'int(exp(-{k}*x),x,0,{b:g})', (1 - mp.exp(-k * b)) / k, 'decay')
    for _ in range(60):
        w = rnd.choice([rnd.randint(1, 100), rnd.randint(100, 10000), rnd.randint(10000, 1000000)])
        add(f'int(cos({w}*x),x,0,1)', mp.sin(w) / w, 'osc')
        add(f'int(sin({w}*x)^2,x,0,1)', mp.mpf(1) / 2 - mp.sin(2 * w) / (4 * w), 'osc')
    for _ in range(10):
        c = mp.mpf(str(round(rnd.uniform(0.01, 0.99), 3)))
        add(f'int(abs(x-{mp.nstr(c, 6)}),x,0,1)', (c ** 2 + (1 - c) ** 2) / 2, 'kink')
        add(f'int(sign(x-{mp.nstr(c, 6)}),x,0,1)', 1 - 2 * c, 'jump')
    for p in ['0.1', '0.3', '0.5', '0.7', '0.9', '0.99']:
        add(f'int(x^(-{p}),x,0,1)', 1 / (1 - mp.mpf(p)), 'endpoint')
    add('int(ln(x),x,0,1)', -1, 'endpoint')
    add('int(1/sqrt(1-x^2),x,-1,1)', mp.pi, 'endpoint')
    add('int(1/sqrt(x),x,0,1)', 2, 'endpoint')
    add('int(ln(abs(x-0.3)),x,0,1)', mp.mpf('0.3') * mp.log(mp.mpf('0.3')) + mp.mpf('0.7') * mp.log(mp.mpf('0.7')) - 1, 'endpoint')
    for _ in range(10):
        n = rnd.randint(0, 8)
        b = rnd.choice([1, 2, 5, 20])
        add(f'int(x^{n}*exp(-x),x,0,{b})', mp.quad(lambda t: t ** n * mp.exp(-t), [0, b]), 'smooth')

    def q(f, a, b, pts=()):
        return mp.quad(f, [a, *pts, b], maxdegree=12)

    sqpi = mp.sqrt(mp.pi)
    special = [
        ('int(exp(-(774.6-x)^2),x,0,100000)', sqpi),
        ('int(exp(-(x^2-1549.2*x+600005.16)),x,0,100000)', sqpi),
        ('int(exp(-(x-774.6)*(x-774.6)),x,0,100000)', sqpi),
        ('int(exp(-((x/1000-0.7746)*1000)^2),x,0,100000)', sqpi),
        ('int(exp(-(x^2-600005.16)^2/1000000),x,0,100000)',
         q(lambda t: mp.exp(-(t ** 2 - mp.mpf('600005.16')) ** 2 / 10 ** 6), 0, 100000, [mp.sqrt(mp.mpf('600005.16'))])),
        ('int(exp(-(ln(x)-6.6524)^2*10000),x,1,100000)',
         q(lambda t: mp.exp(-(mp.log(t) - mp.mpf('6.6524')) ** 2 * 10000), 1, 100000, [mp.exp(mp.mpf('6.6524'))])),
        ('int(exp(-(sqrt(x)-27.83)^2*100),x,0,100000)',
         q(lambda t: mp.exp(-(mp.sqrt(t) - mp.mpf('27.83')) ** 2 * 100), 0, 100000, [mp.mpf('27.83') ** 2])),
        ('int(1/(1+(x^2-1549.2*x+600005.16)*1000000),x,0,100000)',
         mp.atan(1000 * (100000 - mp.mpf('774.6'))) / 1000 + mp.atan(1000 * mp.mpf('774.6')) / 1000),
        ('int(exp(-abs(x-774.6)*1000),x,0,100000)', mp.mpf('0.002')),
        ('int(exp(-(x-300)^2*100)+exp(-(x-700)^2*100),x,0,1000)', 2 * mp.sqrt(mp.pi / 100)),
        ('int(exp(-(3*x-0.9)^2*1e12),x,0,1)', mp.sqrt(mp.pi / mp.mpf(10) ** 12) / 3),
        ('int(exp(-(x^2-0.09)^2*1e12),x,0,1)', q(lambda t: mp.exp(-(t ** 2 - mp.mpf('0.09')) ** 2 * 10 ** 12), 0, 1, [mp.mpf('0.3')])),
        ('int(exp(-(sin(x)-0.5)^2*1e8),x,0,3)',
         q(lambda t: mp.exp(-(mp.sin(t) - mp.mpf('0.5')) ** 2 * 10 ** 8), 0, 3, [mp.asin(mp.mpf('0.5')), mp.pi - mp.asin(mp.mpf('0.5'))])),
        ('int(exp(-(x*x-2)^2*1e10),x,0,10)', q(lambda t: mp.exp(-(t * t - 2) ** 2 * 10 ** 10), 0, 10, [mp.sqrt(2)])),
        ('int(exp(-(x-sqrt(2))^2*1e10),x,0,10)', mp.sqrt(mp.pi / mp.mpf(10) ** 10)),
        ('int(int(exp(-((x-3)^2+(y-2)^2)*10000),y,-10,10),x,-10,10)', mp.pi / 10000),
        ('int(int(exp(-(x^2-6*x+9+y^2-4*y+4)*10000),y,-10,10),x,-10,10)', mp.pi / 10000),
        ('int(x^2*exp(-(x-5000)^2),x,0,100000)', sqpi * (mp.mpf(5000) ** 2 + mp.mpf('0.5'))),
        # int_0^1 sqrt(x)*cos(a*x) = sin(a)/a - sqrt(2*pi/a)*S(sqrt(2*a/pi))/(2*a), S = Fresnel sine integral
        ('int(cos(40000*pi*x)*sqrt(x),x,0,1)', mp.sin(40000 * mp.pi) / (40000 * mp.pi)
         - mp.sqrt(2 * mp.pi / (40000 * mp.pi)) * mp.fresnels(mp.sqrt(2 * 40000 * mp.pi / mp.pi)) / (2 * 40000 * mp.pi)),
    ]
    for expr, ref in special:
        add(expr, ref, 'special')

    # Short intervals far from 0. The reference uses the decimal endpoints exactly; the absolute
    # tolerance allows for rounding the endpoints to double: (|f(a)| + |f(b)|) * ulp(max(|a|, |b|)).
    def ulp(v):
        return math.ulp(float(v))
    short = [
        ('x^2', lambda t: t ** 2, lambda t: t ** 3 / 3, '1000000', '1000000.000001'),
        ('x^2', lambda t: t ** 2, lambda t: t ** 3 / 3, '1000000', '1000000.0001'),
        ('cos(x)', mp.cos, mp.sin, '1', '1.000000000001'),
        ('x', lambda t: t, lambda t: t ** 2 / 2, '100000000', '100000000.001'),
        ('sin(x)', mp.sin, lambda t: -mp.cos(t), '1000000', '1000000.00001'),
        ('exp(x)', mp.exp, mp.exp, '50', '50.00000001'),
        ('x^3', lambda t: t ** 3, lambda t: t ** 4 / 4, '-1000', '1000.000001'),
    ]
    for ftxt, f, big_f, a, b in short:
        am, bm = mp.mpf(a), mp.mpf(b)
        tol = (abs(f(am)) + abs(f(bm))) * ulp(max(abs(am), abs(bm)))
        add(f'int({ftxt},x,{a},{b})', big_f(bm) - big_f(am), 'short', float(tol))
    write('integrals.tsv', rows,
          'Definite integrals with closed-form or high-precision references. check integral: a correct value, '
          'an explicit error, or a result marked as not converged is accepted; a wrong value marked as converged is not.')



def antiderivatives():
    rows = []
    samples = [0.37, 1.3, 2.9, 4.1, 0.81, -0.6, -1.7, -3.3]
    for seed, mode, count in [(11, 'rad', 250), (23, 'deg', 120)]:
        rnd = random.Random(seed)

        def lin():
            a = rnd.choice([1, 2, 3, -1, -2, 5, sp.Rational(1, 2), sp.Rational(-3, 2)])
            b = rnd.choice([0, 0, 1, -1, 2, sp.Rational(1, 3)])
            return a * X + b

        def atom():
            u = lin()
            f = rnd.choice(['sin', 'cos', 'exp', 'ln', 'sqrt', 'pow', 'inv', 'invpow', 'tan', 'sinh', 'cosh', 'poly',
                            'xexp', 'xsin', 'sin2', 'cos2', 'atan'])
            return {
                'sin': lambda: sp.sin(u), 'cos': lambda: sp.cos(u), 'exp': lambda: sp.exp(u), 'ln': lambda: sp.log(u),
                'sqrt': lambda: sp.sqrt(u),
                'pow': lambda: u ** rnd.choice([2, 3, 5, sp.Rational(1, 2), sp.Rational(3, 2), sp.Rational(-1, 2)]),
                'inv': lambda: 1 / u, 'invpow': lambda: 1 / u ** rnd.choice([2, 3]), 'tan': lambda: sp.tan(u),
                'sinh': lambda: sp.sinh(u), 'cosh': lambda: sp.cosh(u),
                'poly': lambda: sum(rnd.randint(-5, 5) * X ** k for k in range(rnd.randint(1, 5))),
                'xexp': lambda: X * sp.exp(u), 'xsin': lambda: X * sp.sin(u), 'sin2': lambda: sp.sin(u) ** 2,
                'cos2': lambda: sp.cos(u) ** 2, 'atan': lambda: 1 / (1 + X ** 2),
            }[f]()

        seen = set()
        made = 0
        while made < count:
            k = rnd.random()
            if k < 0.55:
                e = rnd.randint(1, 4) * atom()
            elif k < 0.85:
                e = atom() + atom()
            else:
                e = atom() / rnd.choice([2, 3, 5])
            t = sp.sstr(e).replace('**', '^').replace('log(', 'ln(').replace(' ', '')
            if t in seen:
                continue
            seen.add(t)
            g = e
            if mode == 'deg':
                g = e.replace(sp.sin, lambda a: sp.sin(a * sp.pi / 180)).replace(
                    sp.cos, lambda a: sp.cos(a * sp.pi / 180)).replace(sp.tan, lambda a: sp.tan(a * sp.pi / 180))
            pts = []
            for x0 in samples:
                try:
                    v = complex(g.subs(X, x0).evalf(30))
                except (TypeError, ValueError, ZeroDivisionError):
                    continue
                if v.imag == 0 and math.isfinite(v.real):
                    pts.append(f'{num(x0)}:{num(v.real)}')
                if len(pts) == 3:
                    break
            if not pts:
                continue
            expr = f'integral({t},x)'
            rows.append([f'anti_{mode}_{len(rows):04d}', expr, expr, 'antiderivative', ';'.join(pts), '1e-9', '1e-6', mode])
            made += 1
    write('antiderivatives.tsv', rows,
          'Random integrands. antiderivative: the result F must satisfy F\'(x0) = f(x0) at the sample points x0:f(x0); '
          '"Symbolische Integration nicht möglich" counts as unsupported, not as a failure.')



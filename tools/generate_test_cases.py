def matrices():
    rnd = random.Random(3)

    def entry():
        r = rnd.random()
        if r < 0.3:
            return str(rnd.randint(-9, 9))
        if r < 0.5:
            return f'{rnd.randint(1, 9)}/{rnd.randint(2, 9)}'
        e = rnd.choice([-20, -15, -10, -7, -3, 0, 3, 7, 10, 15, 20])
        return f'{rnd.uniform(-9.99, 9.99):.3g}e{e}'

    def exact(s):
        if '/' in s:
            a, b = s.split('/')
            return mp.mpf(a) / mp.mpf(b)
        return mp.mpf(s)

    def text(m):
        return '[' + ','.join('[' + ','.join(r) + ']' for r in m) + ']'

    def enc(mat):
        return '[' + ','.join('[' + ','.join(num(mat[i, j]) for j in range(mat.cols)) + ']' for i in range(mat.rows)) + ']'

    def absm(mat):
        return mp.matrix([[abs(mat[i, j]) for j in range(mat.cols)] for i in range(mat.rows)])

    rows = []
    while len(rows) < 600:
        n = rnd.choice([2, 2, 3, 3, 4])
        m = [[entry() for _ in range(n)] for _ in range(n)]
        a = mp.matrix([[exact(v) for v in r] for r in m])
        det = mp.det(a)
        if det == 0:
            continue
        inv = a ** -1
        b_txt = [[entry() for _ in range(n)] for _ in range(n)]
        b = mp.matrix([[exact(v) for v in r] for r in b_txt])
        cond = mp.mnorm(a, 1) * mp.mnorm(inv, 1)
        t = text(m)
        k = len(rows)
        # Expected matrix ; componentwise error bound |inv|*|A|*|inv| (perturbation of A by one rounding per entry)
        rows.append([f'mat_inv_{k:04d}', f'inv({t})', f'inv({t})', 'matrix', enc(inv) + ';' + enc(absm(inv) * absm(a) * absm(inv)), '0', '1e-9', 'rad'])
        rows.append([f'mat_det_{k + 1:04d}', f'det({t})', f'det({t})', 'number', num(det), '0', num(min(1e-3, 1e-9 * max(1.0, float(cond)))), 'rad'])
        rows.append([f'mat_mul_{k + 2:04d}', f'{t}*{text(b_txt)}', f'{t}*{text(b_txt)}', 'matrix', enc(a * b) + ';' + enc(absm(a) * absm(b)), '0', '1e-9', 'rad'])
        eye = mp.eye(n)
        bound = absm(a) * absm(inv) * absm(a) * absm(inv)
        rows.append([f'mat_ainv_{k + 3:04d}', f'{t}*inv({t})', f'{t}*inv({t})', 'matrix', enc(eye) + ';' + enc(bound), '0', '1e-9', 'rad'])
    write('matrices.tsv', rows,
          'Random 2x2 to 4x4 matrices with entries from 1e-20 to 1e20. matrix: expected;bound. An entry passes if '
          '|actual-expected| <= rel*|expected| + 1e4*eps*bound, plus the rounding of the displayed digits.')


